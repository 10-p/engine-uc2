#!/usr/bin/env python3
"""Remove GCC_PACK(4) from bitfield members that continue a run of bitfields.

Epic's header exporter (Editor/Src/UnEdExp.cpp) tags a bool with GCC_PACK(4) when the previous bool differs in
CPF_Transient ("do not allow transient/non-transient bools to be packed together"). The script linker has no
such rule (UBoolProperty::Link merges every bool with the previous one) and MSVC ignores GCC_PACK, so the tag
only ever changed GCC's layout: it starts a new 32-bit word in the middle of a run and shifts everything after
it. The tag on the FIRST bitfield of a run is correct (script aligns there too) and is kept.

A second rule, for headers generated from script only (the ones with the "automatically generated" banner):
the first data member of a class gets GCC_PACK(4) unless it is a bitfield (those are tagged already). Without
it GCC places a small first member (BYTE, _WORD) in the unused tail bytes of the parent class, which MSVC and
the script linker never do. engine-ut2004's exporter has this rule (LastIt == NULL); UC2's had lost it.

  tools/dev/fix-bitfield-pack.py [--check] <header>...
"""
import re, sys

BIT = re.compile(rb'^(\s*BITFIELD\s+\w+\s*:\s*1)(\s+GCC_PACK\(\d+\))?(\s*;.*)$')

def fix(path, write):
    lines = open(path, 'rb').read().split(b'\n')
    in_run = False
    changed = 0
    for i, line in enumerate(lines):
        m = BIT.match(line.rstrip(b'\r'))
        if not m:
            if line.strip():            # any other declaration ends the run; blank lines do not
                in_run = False
            continue
        if in_run and m.group(2):
            cr = b'\r' if line.endswith(b'\r') else b''
            lines[i] = m.group(1) + m.group(3) + cr
            changed += 1
        in_run = True
    if changed and write:
        open(path, 'wb').write(b'\n'.join(lines))
    return changed

CLASS = re.compile(rb'^class\s+\w+_API\s+\w+\s*:\s*public\s+\w+\s*$')
MEMBER = re.compile(rb'^(\s+(?:class\s+)?[A-Za-z_][\w:<>,\s\*]*?[\s\*]\w+(?:\[\w+\])?)(\s*;.*)$')

def fix_first_member(path, write):
    data = open(path, 'rb').read()
    if b'automatically generated by the tools' not in data:
        return 0
    lines = data.split(b'\n')
    changed = 0
    for i, line in enumerate(lines):
        if not CLASS.match(line.rstrip(b'\r')):
            continue
        j = i + 1
        while j < len(lines) and lines[j].strip() in (b'{', b'public:', b''):
            j += 1
        if j >= len(lines):
            continue
        cand = lines[j].rstrip(b'\r')
        if b'(' in cand or b'BITFIELD' in cand or b'GCC_PACK' in cand or cand.lstrip().startswith(b'#'):
            continue
        m = MEMBER.match(cand)
        if not m:
            continue
        cr = b'\r' if lines[j].endswith(b'\r') else b''
        lines[j] = m.group(1) + b' GCC_PACK(4)' + m.group(2) + cr
        changed += 1
    if changed and write:
        open(path, 'wb').write(b'\n'.join(lines))
    return changed

if __name__ == '__main__':
    args = sys.argv[1:]
    write = '--check' not in args
    total = 0
    for p in [a for a in args if a != '--check']:
        n = fix(p, write)
        total += n
        if n:
            print(f'{p}: {n} mid-run GCC_PACK tag(s) {"removed" if write else "found"}')
        n = fix_first_member(p, write)
        total += n
        if n:
            print(f'{p}: {n} first member(s) {"tagged" if write else "untagged"}')
    print(f'total: {total}')
